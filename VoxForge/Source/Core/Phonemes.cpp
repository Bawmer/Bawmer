int phonemeCount() noexcept { return (int) (sizeof (kTable) / sizeof (kTable[0])); }

const PhonemeInfo& phonemeAt (int index) noexcept
{
    return kTable[juce::jlimit (0, phonemeCount() - 1, index)];
}

int phonemeIndex (const juce::String& arpabet) noexcept
{
    auto s = arpabet.trim().toLowerCase().retainCharacters ("abcdefghijklmnopqrstuvwxyz");
    if (s.isEmpty()) return -1;
    if (s == "pau" || s == "sp" || s == "sil") return 0;
    if (s == "axr") s = "er";
    if (s == "ix")  s = "ih";
    if (s == "ux")  s = "uw";
    if (s == "el")  s = "l";
    if (s == "em")  s = "m";
    if (s == "en")  s = "n";
    if (s == "dx")  s = "d";
    for (int i = 0; i < phonemeCount(); ++i)
        if (s == kTable[i].name)
            return i;
    return -1;
}

bool isVowel (int index) noexcept
{
    return index > 0 && isVowelClass (phonemeAt (index).cls);
}

